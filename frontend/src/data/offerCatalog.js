// Matches a free-text item name against a catalog key (both directions,
// case-insensitive substring). Returns the catalog key or null.
export function matchCatalogKey(itemText) {
  const normalized = String(itemText || '').trim().toLowerCase()
  if (!normalized) return null
  const keys = Object.keys(offerCatalog)
  return (
    keys.find((key) => normalized.includes(key) || key.includes(normalized)) || null
  )
}
